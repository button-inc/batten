//! A nextest step keeps every case it finishes (CLOUD-2772): `step run` runs a
//! `cargo nextest run` with each case's pass written the moment it passes, so a run that stops — a failure, a kill —
//! resumes without re-running a case that passed over the same binary and
//! non-Rust inputs.

use crate::common;

/// The fixture crate: one case that always passes, and one that fails while
/// `fail` exists in the log directory. Each appends a line to its own count.
const LIB: &str = "#[cfg(test)]\nmod tests {\n\
    fn log(name: &str) {\n\
        use std::io::Write as _;\n\
        let dir = std::path::PathBuf::from(std::env::var(\"FIXTURE_LOG\").unwrap());\n\
        let mut file = std::fs::OpenOptions::new().create(true).append(true).open(dir.join(name)).unwrap();\n\
        writeln!(file, \"ran\").unwrap();\n\
    }\n\
    #[test]\n    fn counted() {\n        log(\"counted\");\n    }\n\
    #[test]\n    fn flaky() {\n        log(\"flaky\");\n\
        let dir = std::path::PathBuf::from(std::env::var(\"FIXTURE_LOG\").unwrap());\n\
        assert!(!dir.join(\"fail\").exists(), \"asked to fail\");\n    }\n}\n";

/// How many times the case `name` ran.
fn runs(log: &std::path::Path, name: &str) -> usize {
    std::fs::read_to_string(log.join(name)).map_or(0, |text| text.lines().count())
}

/// A committed checkout of the [`LIB`] fixture with a `suite` step whose row
/// journals its nextest run.
fn journal_fixture(name: &str) -> std::path::PathBuf {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let repo = common::scratch_repo(name);
    common::write(
        &repo,
        "Cargo.toml",
        "[package]\nname = \"fix\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n",
    );
    common::write(&repo, "src/lib.rs", LIB);
    // A CHECKOUT TRACKS ITS LOCKFILE: left to the first build, it appears as a
    // new non-Rust input and every later run reads a moved input state.
    common::write(
        &repo,
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\nversion = 4\n\n\
         [[package]]\nname = \"fix\"\nversion = \"0.1.0\"\n",
    );
    common::write(&repo, ".gitignore", "target/\n");
    common::write(&repo, "notes.txt", "a non-Rust input\n");
    common::write(
        &repo,
        "batten.toml",
        "version = 1\n\n[[step]]\nid = \"suite\"\ninputs = [\".\"]\n\
         tools = [[\"cargo\", \"--version\"]]\njournal = \"nextest\"\n",
    );
    common::git_in(&repo, &["add", "-A"]);
    common::git_in(&repo, &["commit", "-qm", "seed"]);
    repo
}

/// A run that stops keeps every case it passed; the next run, over the same
/// binary and inputs, runs only what did not pass; a moved non-Rust input runs
/// every case again.
///
/// Fails by: a passed case re-run after a failed run (the journal unread, or
/// unwritten), a failed case skipped (a failure journaled as a pass), or a case
/// skipped over a moved input (a stale pass reused).
#[test]
fn a_journaled_step_runs_each_passed_case_once_per_input_state() {
    let repo = journal_fixture("step-journal");
    let log = common::scratch("step-journal-log");
    // THE RECEIPT IS BYPASSED, the journal is not: this fixture's failure
    // switch is a file outside the tree, which no step key can see, so a step
    // receipt would answer the red run's re-run from its failure (CLOUD-2253).
    let step = || {
        let output = common::batten()
            .args(["step", "run", "suite", "--", "cargo", "nextest", "run"])
            .current_dir(&repo)
            .env("FIXTURE_LOG", &log)
            .env("BATTEN_STEP_RECEIPT_BYPASS", "1")
            .env_remove("CI")
            .streamed_output()
            .expect("run batten");
        (output.status.success(), common::stderr(&output))
    };
    std::fs::write(log.join("fail"), "").unwrap();
    let (passed, err) = step();
    assert!(!passed, "a failing case fails the step\n{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (1, 1),
        "{err}"
    );
    let (passed, err) = step();
    assert!(!passed, "{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (1, 2),
        "the passed case is kept, the failed one runs again\n{err}"
    );
    std::fs::remove_file(log.join("fail")).unwrap();
    let (passed, err) = step();
    assert!(passed, "{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (1, 3),
        "{err}"
    );
    common::write(&repo, "notes.txt", "the input moved\n");
    common::git_in(&repo, &["commit", "-qam", "move an input"]);
    let (passed, err) = step();
    assert!(passed, "{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (2, 4),
        "a moved non-Rust input runs every case again\n{err}"
    );
}

/// `step run suite` over [`journal_fixture`] with `env` set and `CI` and the
/// receipt bypass otherwise removed: whether it passed and what it said.
fn journal_step(
    repo: &std::path::Path,
    log: &std::path::Path,
    env: (&str, &str),
) -> (bool, String) {
    let output = common::batten()
        .args(["step", "run", "suite", "--", "cargo", "nextest", "run"])
        .current_dir(repo)
        .env("FIXTURE_LOG", log)
        .env_remove("CI")
        .env_remove("BATTEN_STEP_RECEIPT_BYPASS")
        .env(env.0, env.1)
        .streamed_output()
        .expect("run batten");
    (output.status.success(), common::stderr(&output))
}

/// CI confirms independently (CLOUD-2850): under `CI` a journaled step runs
/// every case on every run, however many a journal holds as passed.
///
/// Fails by: a passed case answered from the journal on a CI runner.
#[test]
fn under_ci_a_journaled_step_runs_every_case_every_time() {
    let repo = journal_fixture("step-journal-ci");
    let log = common::scratch("step-journal-ci-log");
    for run in 1..=2 {
        let (passed, err) = journal_step(&repo, &log, ("CI", "true"));
        assert!(passed, "{err}");
        assert_eq!(
            (runs(&log, "counted"), runs(&log, "flaky")),
            (run, run),
            "run {run}: every case runs again under CI\n{err}"
        );
    }
}

/// The receipt bypass is not CI (CLOUD-2850): it switches off the step
/// receipt alone, and the journal still keeps every passed case.
///
/// Fails by: a journal gated on every bypass rather than on `CI` alone, so a
/// passed case runs again.
#[test]
fn the_receipt_bypass_keeps_the_journal() {
    let repo = journal_fixture("step-journal-bypass");
    let log = common::scratch("step-journal-bypass-log");
    for _ in 1..=2 {
        let (passed, err) = journal_step(&repo, &log, ("BATTEN_STEP_RECEIPT_BYPASS", "1"));
        assert!(passed, "{err}");
        assert_eq!(
            (runs(&log, "counted"), runs(&log, "flaky")),
            (1, 1),
            "a passed case is kept under the bypass\n{err}"
        );
    }
}

/// The cross-head fixture: three library functions, one reading a template
/// the build includes, and a case for each beside one no record names. Each
/// case appends a line to its own count.
const SELECTED: &str = "const TEMPLATE: &str = include_str!(\"../tpl.txt\");\n\
    pub fn alpha() -> u8 { u8::from(!TEMPLATE.is_empty()) }\n\
    pub fn beta() -> u8 { 2 }\n\
    pub fn gamma() -> u8 { helper::three() }\n\
    #[cfg(test)]\nmod tests {\n\
    fn log(name: &str) {\n\
        use std::io::Write as _;\n\
        let dir = std::path::PathBuf::from(std::env::var(\"FIXTURE_LOG\").unwrap());\n\
        let mut file = std::fs::OpenOptions::new().create(true).append(true).open(dir.join(name)).unwrap();\n\
        writeln!(file, \"ran\").unwrap();\n\
    }\n\
    #[test]\n    fn uses_alpha() {\n        log(\"uses_alpha\");\n        assert_eq!(super::alpha(), 1);\n    }\n\
    #[test]\n    fn uses_beta() {\n        log(\"uses_beta\");\n        assert_eq!(super::beta(), 2);\n    }\n\
    #[test]\n    fn uses_gamma() {\n        log(\"uses_gamma\");\n        assert_eq!(super::gamma(), 3);\n    }\n\
    #[test]\n    fn unrecorded() {\n        log(\"unrecorded\");\n    }\n}\n";

/// The fixture's second workspace package, which no sweep probes: what
/// `gamma` returns.
const HELPER: &str = "pub fn three() -> u8 { 3 }\n";

/// A committed checkout of the cross-head fixture with a `suite` step, and
/// the sweep's reach store seeded as a sweep over it would have sealed it:
/// each of `uses_alpha`, `uses_beta` and `uses_gamma` recorded running its
/// function and the shared helper, `uses_beta` reading `data.txt`, and
/// `unrecorded` absent.
fn selected_repo(name: &str) -> std::path::PathBuf {
    selected_repo_with(name, SELECTED)
}

/// [`selected_repo`] with `source` as the fixture's `src/lib.rs`, which must
/// keep [`SELECTED`]'s functions and cases.
fn selected_repo_with(name: &str, source: &str) -> std::path::PathBuf {
    use batten::mutate::schema;
    let repo = common::scratch_repo(name);
    common::write(
        &repo,
        "Cargo.toml",
        "[package]\nname = \"fix\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n\
         [dependencies]\nhelper = { path = \"helper\" }\n\n[workspace]\nmembers = [\"helper\"]\n",
    );
    common::write(&repo, "src/lib.rs", source);
    common::write(
        &repo,
        "helper/Cargo.toml",
        "[package]\nname = \"helper\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    );
    common::write(&repo, "helper/src/lib.rs", HELPER);
    common::write(
        &repo,
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\nversion = 4\n\n\
         [[package]]\nname = \"fix\"\nversion = \"0.1.0\"\ndependencies = [\n \"helper\",\n]\n\n\
         [[package]]\nname = \"helper\"\nversion = \"0.1.0\"\n",
    );
    common::write(&repo, ".gitignore", "target/\n");
    common::write(&repo, "tpl.txt", "a template\n");
    common::write(&repo, "data.txt", "a runtime fixture\n");
    common::write(
        &repo,
        "batten.toml",
        "version = 1\n\n[[step]]\nid = \"suite\"\ninputs = [\".\"]\n\
         tools = [[\"cargo\", \"--version\"]]\njournal = \"nextest\"\n",
    );
    common::git_in(&repo, &["add", "-A"]);
    common::git_in(&repo, &["commit", "-qm", "seed"]);
    let _ = common::scratch_state_root();
    let base = batten::state::repo_state_dir(&repo)
        .expect("the state dir")
        .join("mutate")
        .join("schema")
        .join("reach");
    let format = schema::Format {
        dirs: [(String::from("fix"), String::new())].into(),
        probed: [String::from("src/lib.rs")].into(),
        flags: schema::build_flags(),
        ..schema::Format::default()
    };
    let index = schema::dependency_index(&repo, &format).expect("index the fixture");
    common::write(&base, "tree", "seed");
    for (case, function, read) in [
        ("uses_alpha", "alpha", ""),
        ("uses_beta", "beta", "data.txt\n"),
        ("uses_gamma", "gamma", ""),
    ] {
        let mut depends = String::from("D-\n");
        for name in [case, function, "log"] {
            let digests = index.digests_of(name);
            assert!(!digests.is_empty(), "{name} is probed");
            for digest in digests {
                depends.push('F');
                depends.push_str(&digest);
                depends.push('\n');
            }
        }
        let dir = base.join(case);
        common::write(&dir, "case", &format!("tests::{case}\tfix"));
        common::write(&dir, "over", "seed");
        common::write(&dir, "done", "0");
        common::write(&dir, "read", read);
        common::write(&dir, "depends", &depends);
    }
    let resources = schema::resource_ids(&repo).expect("the fixture's content ids");
    assert_eq!(
        schema::seal_tested(&base, &repo, &resources, &format).expect("seal"),
        3,
        "every recorded case takes a selection digest"
    );
    repo
}

/// `step run suite -- cargo nextest run` in `repo`, each case's count under
/// `log`: whether it passed and what it said.
fn selected_step(repo: &std::path::Path, log: &std::path::Path) -> (bool, String) {
    let output = common::batten()
        .args(["step", "run", "suite", "--", "cargo", "nextest", "run"])
        .current_dir(repo)
        .env("FIXTURE_LOG", log)
        .env_remove("CI")
        .streamed_output()
        .expect("run batten");
    (output.status.success(), common::stderr(&output))
}

/// Each case's run count under `log`, in the fixture's order.
fn counts(log: &std::path::Path) -> [usize; 4] {
    ["uses_alpha", "uses_beta", "uses_gamma", "unrecorded"].map(|name| runs(log, name))
}

/// Across heads, a case recorded by the sweep reruns only when something it
/// ran moved: an edit to a function nothing recorded calls reruns none of
/// them, an edit to one case's function reruns that case, and a case with no
/// record reruns on every head.
///
/// Fails by: a recorded case rerun over an edit it never reached (the
/// dependency key unread, or keyed on the binary), a case skipped over an edit
/// to a function it ran (a stale pass reused), or an unrecorded case skipped.
#[test]
fn a_recorded_case_reruns_only_when_a_function_it_ran_moved() {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let repo = selected_repo("step-select-fn");
    let log = common::scratch("step-select-fn-log");
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(counts(&log), [1, 1, 1, 1], "{err}");
    common::write(
        &repo,
        "src/lib.rs",
        &SELECTED.replace("#[cfg(test)]", "pub fn delta() -> u8 { 4 }\n#[cfg(test)]"),
    );
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(
        counts(&log),
        [1, 1, 1, 2],
        "a function no recorded case reaches reruns none of them\n{err}"
    );
    common::write(
        &repo,
        "src/lib.rs",
        &SELECTED.replace("pub fn beta() -> u8 { 2 }", "pub fn beta() -> u8 { 1 + 1 }"),
    );
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(
        counts(&log),
        [1, 2, 1, 3],
        "an edit to the function one case ran reruns that case alone\n{err}"
    );
}

/// A file a recorded case read at run time, or one its code holds by an
/// include, reruns that case and no other.
///
/// Fails by: a case skipped over a moved fixture it read or a moved file its
/// code includes (a stale pass of a rebuilt constant), or a case rerun over a
/// file it neither read nor holds.
#[test]
fn a_moved_file_a_recorded_case_read_or_includes_reruns_it_alone() {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let repo = selected_repo("step-select-file");
    let log = common::scratch("step-select-file-log");
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(counts(&log), [1, 1, 1, 1], "{err}");
    common::write(&repo, "data.txt", "the fixture moved\n");
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(
        counts(&log),
        [1, 2, 1, 2],
        "a moved runtime fixture reruns the case that read it\n{err}"
    );
    common::write(&repo, "tpl.txt", "the template moved\n");
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    let [alpha, _, gamma, _] = counts(&log);
    assert_eq!(
        (alpha, gamma),
        (2, 1),
        "a moved include reruns the case whose code holds it, and no other\n{err}"
    );
}

/// An edit to a workspace package the sweep never probed reruns every
/// recorded case, though no record names a function of it and no name a case
/// reaches leads there: the conservative fold, since a record cannot say which
/// cases run code it never probed.
///
/// Fails by: a recorded case skipped over an edit to a package no record
/// covers (a stale pass reused wherever that code is reached by an edge no
/// name shows), or an unmoved tree rerunning anything.
#[test]
fn an_edit_to_an_unprobed_workspace_package_reruns_a_recorded_case() {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let repo = selected_repo("step-select-unprobed");
    let log = common::scratch("step-select-unprobed-log");
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(counts(&log), [1, 1, 1, 1], "{err}");
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(
        counts(&log),
        [1, 1, 1, 1],
        "an unmoved tree reruns nothing\n{err}"
    );
    common::write(
        &repo,
        "helper/src/lib.rs",
        &format!("{HELPER}pub fn four() -> u8 {{ 4 }}\n"),
    );
    let (passed, err) = selected_step(&repo, &log);
    assert!(passed, "{err}");
    assert_eq!(
        counts(&log),
        [2, 2, 2, 2],
        "an unprobed package's edit reruns every recorded case\n{err}"
    );
}

/// The cross-head fixture with `uses_alpha` failing while `FIXTURE_FAIL` is
/// set: a failure no edit to the tree causes.
fn flaky_source() -> String {
    SELECTED.replace(
        "log(\"uses_alpha\");",
        "log(\"uses_alpha\");\n        assert!(std::env::var_os(\"FIXTURE_FAIL\").is_none(), \"asked to fail\");",
    )
}

/// `step run suite -- cargo nextest run` in `repo` with `uses_alpha` asked to
/// fail: whether it passed and what it said.
fn failing_step(repo: &std::path::Path, log: &std::path::Path) -> (bool, String) {
    let output = common::batten()
        .args(["step", "run", "suite", "--", "cargo", "nextest", "run"])
        .current_dir(repo)
        .env("FIXTURE_LOG", log)
        .env("FIXTURE_FAIL", "1")
        .env_remove("CI")
        .streamed_output()
        .expect("run batten");
    (output.status.success(), common::stderr(&output))
}

/// The listing a `flaky-suspect` line points at, and the line's counts.
fn flaky_line(err: &str) -> (String, String) {
    let (counts, listing) = err
        .lines()
        .find_map(|line| line.strip_prefix("step run: suite flaky-suspect "))
        .and_then(|rest| rest.split_once(" failing case(s); read "))
        .unwrap_or_else(|| panic!("a failing journaled run labels its failures: {err}"));
    (
        counts.to_owned(),
        std::fs::read_to_string(listing.trim()).expect("the listing is written"),
    )
}

/// A red journaled run says whether the change could have caused it: a
/// failing case whose recorded reach still holds on this tree ran nothing
/// that moved, so it is a flaky suspect; once a function it ran moves, it is
/// not. The exit is the suite's either way: red is never reused.
///
/// Fails by: a failure off the change unlabelled (the reach store unread, or
/// the report unread), a failure a moved function may have caused labelled
/// (a real regression dismissed as flaky), or the label turning red green.
#[test]
fn a_failure_off_the_change_is_labelled_flaky_suspect() {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let source = flaky_source();
    let repo = selected_repo_with("step-flaky", &source);
    let log = common::scratch("step-flaky-log");
    let (passed, err) = failing_step(&repo, &log);
    assert!(!passed, "the label never turns red green\n{err}");
    let (counts, listing) = flaky_line(&err);
    assert_eq!(counts, "1 of 1", "{err}");
    assert_eq!(listing, "fix tests::uses_alpha\n", "{err}");
    common::write(
        &repo,
        "src/lib.rs",
        &source.replace(
            "u8::from(!TEMPLATE.is_empty())",
            "u8::from(TEMPLATE.len() > 0)",
        ),
    );
    let (passed, err) = failing_step(&repo, &log);
    assert!(!passed, "{err}");
    let (counts, listing) = flaky_line(&err);
    assert_eq!(
        counts, "0 of 1",
        "a failing case whose function moved is the change's to answer for\n{err}"
    );
    assert_eq!(listing, "", "{err}");
}

/// `step run suite -- cargo nextest run` in `repo`, `uses_alpha` failing iff
/// `fail`: whether it passed and what it said.
fn suite_step(repo: &std::path::Path, log: &std::path::Path, fail: bool) -> (bool, String) {
    let mut command = common::batten();
    command
        .args(["step", "run", "suite", "--", "cargo", "nextest", "run"])
        .current_dir(repo)
        .env("FIXTURE_LOG", log)
        .env_remove("CI")
        .env_remove("BATTEN_STEP_RECEIPT_BYPASS");
    if fail {
        command.env("FIXTURE_FAIL", "1");
    } else {
        command.env_remove("FIXTURE_FAIL");
    }
    let output = command.streamed_output().expect("run batten");
    (output.status.success(), common::stderr(&output))
}

/// A failure whose every failing case is a flaky suspect (its recorded reach
/// misses the change) is re-run over the same inputs, and a pass at that key
/// replaces the failure receipt (CLOUD-2253, CLOUD-2786).
///
/// Fails by: a flaky-suspect failure answered from its receipt (red reused
/// where the change cannot have caused it), or a later pass leaving the
/// failure in place so the next run re-runs or reports red.
#[test]
fn a_flaky_suspect_failure_re_runs_and_a_pass_replaces_it() {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let repo = selected_repo_with("step-red-flaky", &flaky_source());
    let log = common::scratch("step-red-flaky-log");
    let (passed, err) = suite_step(&repo, &log, true);
    assert!(!passed, "{err}");
    assert_eq!(flaky_line(&err).0, "1 of 1", "{err}");
    let (passed, err) = suite_step(&repo, &log, true);
    assert!(!passed, "{err}");
    assert_eq!(counts(&log)[0], 2, "a flaky-suspect failure re-runs\n{err}");
    let (passed, err) = suite_step(&repo, &log, false);
    assert!(passed, "{err}");
    assert_eq!(counts(&log)[0], 3, "{err}");
    let (passed, err) = suite_step(&repo, &log, true);
    assert!(passed, "the pass replaced the failure receipt\n{err}");
    assert_eq!(err.split_whitespace().next(), Some("hit"), "{err}");
    assert_eq!(counts(&log)[0], 3, "a hit runs nothing\n{err}");
}

/// A failing suite names exactly its failing cases and the focused command
/// that confirms a fix, as one pointer line, and says it again when the
/// failure is answered from its receipt; the command runs the failing case
/// and no other.
///
/// Fails by: the line missing or naming a passing case, a filter that does
/// not select the failing case alone, or a receipt-answered failure losing it.
#[test]
fn a_failing_suite_names_its_cases_and_a_focused_command() {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let repo = selected_repo_with("step-red-focus", &flaky_source());
    // THE CHANGE REACHES THE FAILING CASE, committed so the step has a key: a
    // failure the change may have caused is the change's, never flaky.
    common::write(
        &repo,
        "src/lib.rs",
        &flaky_source().replace(
            "u8::from(!TEMPLATE.is_empty())",
            "u8::from(TEMPLATE.len() > 0)",
        ),
    );
    common::git_in(&repo, &["commit", "-qam", "move alpha"]);
    let log = common::scratch("step-red-focus-log");
    let expected = "step run: suite failed 1 case(s): fix tests::uses_alpha; confirm a fix with: \
                    cargo nextest run -E '(binary_id(fix) & test(=tests::uses_alpha))'";
    let (passed, err) = suite_step(&repo, &log, true);
    assert!(!passed, "{err}");
    assert_eq!(flaky_line(&err).0, "0 of 1", "the change reaches it\n{err}");
    assert!(err.lines().any(|line| line == expected), "{err}");
    let (passed, again) = suite_step(&repo, &log, true);
    assert!(!passed, "{again}");
    assert_eq!(again.split_whitespace().next(), Some("red"), "{again}");
    assert!(again.lines().any(|line| line == expected), "{again}");
    assert_eq!(
        counts(&log),
        [1, 1, 1, 1],
        "answered from the receipt\n{again}"
    );
    let command = expected.split_once("confirm a fix with: ").unwrap().1;
    let confirmed = common::task_bash(&repo, command)
        .env("FIXTURE_LOG", &log)
        .env("FIXTURE_FAIL", "1")
        .streamed_output()
        .expect("run the focused command");
    let said = String::from_utf8_lossy(&confirmed.stderr);
    assert!(!confirmed.status.success(), "it still fails\n{said}");
    assert_eq!(
        counts(&log),
        [2, 1, 1, 1],
        "the failing case and no other\n{said}"
    );
}
