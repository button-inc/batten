//! A nextest step keeps every case it finishes (CLOUD-2772): `step run` runs a
//! `cargo nextest run` with each case's pass written the moment it passes, so a run that stops — a failure, a kill —
//! resumes without re-running a case that passed over the same binary and
//! non-Rust inputs.

use crate::common;

/// The fixture crate: one case that always passes, and one that fails while
/// `fail` exists in the log directory. Each appends a line to its own count.
const LIB: &str = "#[cfg(test)]\nmod tests {\n\
    fn log(name: &str) {\n\
        use std::io::Write as _;\n\
        let dir = std::path::PathBuf::from(std::env::var(\"FIXTURE_LOG\").unwrap());\n\
        let mut file = std::fs::OpenOptions::new().create(true).append(true).open(dir.join(name)).unwrap();\n\
        writeln!(file, \"ran\").unwrap();\n\
    }\n\
    #[test]\n    fn counted() {\n        log(\"counted\");\n    }\n\
    #[test]\n    fn flaky() {\n        log(\"flaky\");\n\
        let dir = std::path::PathBuf::from(std::env::var(\"FIXTURE_LOG\").unwrap());\n\
        assert!(!dir.join(\"fail\").exists(), \"asked to fail\");\n    }\n}\n";

/// How many times the case `name` ran.
fn runs(log: &std::path::Path, name: &str) -> usize {
    std::fs::read_to_string(log.join(name)).map_or(0, |text| text.lines().count())
}

/// A run that stops keeps every case it passed; the next run, over the same
/// binary and inputs, runs only what did not pass; a moved non-Rust input runs
/// every case again.
///
/// Fails by: a passed case re-run after a failed run (the journal unread, or
/// unwritten), a failed case skipped (a failure journaled as a pass), or a case
/// skipped over a moved input (a stale pass reused).
#[test]
fn a_journaled_step_runs_each_passed_case_once_per_input_state() {
    let _ = common::require_bin("nextest", "cargo-nextest");
    let repo = common::scratch_repo("step-journal");
    common::write(
        &repo,
        "Cargo.toml",
        "[package]\nname = \"fix\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n",
    );
    common::write(&repo, "src/lib.rs", LIB);
    // A CHECKOUT TRACKS ITS LOCKFILE: left to the first build, it appears as a
    // new non-Rust input and every later run reads a moved input state.
    common::write(
        &repo,
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\nversion = 4\n\n\
         [[package]]\nname = \"fix\"\nversion = \"0.1.0\"\n",
    );
    common::write(&repo, ".gitignore", "target/\n");
    common::write(&repo, "notes.txt", "a non-Rust input\n");
    common::write(
        &repo,
        "batten.toml",
        "version = 1\n\n[[step]]\nid = \"suite\"\ninputs = [\".\"]\n\
         tools = [[\"cargo\", \"--version\"]]\n",
    );
    common::git_in(&repo, &["add", "-A"]);
    common::git_in(&repo, &["commit", "-qm", "seed"]);
    let log = common::scratch("step-journal-log");
    let step = || {
        let output = common::batten()
            .args(["step", "run", "suite", "--", "cargo", "nextest", "run"])
            .current_dir(&repo)
            .env("FIXTURE_LOG", &log)
            .output()
            .expect("run batten");
        (output.status.success(), common::stderr(&output))
    };
    std::fs::write(log.join("fail"), "").unwrap();
    let (passed, err) = step();
    assert!(!passed, "a failing case fails the step\n{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (1, 1),
        "{err}"
    );
    let (passed, err) = step();
    assert!(!passed, "{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (1, 2),
        "the passed case is kept, the failed one runs again\n{err}"
    );
    std::fs::remove_file(log.join("fail")).unwrap();
    let (passed, err) = step();
    assert!(passed, "{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (1, 3),
        "{err}"
    );
    common::write(&repo, "notes.txt", "the input moved\n");
    common::git_in(&repo, &["commit", "-qam", "move an input"]);
    let (passed, err) = step();
    assert!(passed, "{err}");
    assert_eq!(
        (runs(&log, "counted"), runs(&log, "flaky")),
        (2, 4),
        "a moved non-Rust input runs every case again\n{err}"
    );
}
